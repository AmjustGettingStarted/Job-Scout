import { mergeProps } from "@base-ui/react/merge-props"
import { useRender } from "@base-ui/react/use-render"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "cn"

const badgeVariants = cva(
  "group/badge inline-flex h-6 w-fit shrink-0 items-center justify-center gap-1 overflow-hidden rounded-buttons border border-transparent px-2.5 py-0.5 text-caption font-semibold whitespace-nowrap transition-all focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/50 has-data-[icon=inline-end]:pr-1.5 has-data-[icon=inline-start]:pl-1.5 aria-invalid:border-destructive aria-invalid:ring-destructive/20 [&>svg]:pointer-events-none [&>svg]:size-3!",
  {
    variants: {
      variant: {
        default:
          "border-crimson-line bg-plasma-wash text-plasma-pink [a]:hover:bg-plasma-wash",
        secondary:
          "border-hairline bg-secondary text-secondary-foreground [a]:hover:bg-secondary/80",
        destructive:
          "border-crimson-line bg-plasma-wash text-plasma-pink [a]:hover:bg-plasma-wash",
        outline:
          "border-crimson-line text-frost-white [a]:hover:bg-plasma-wash",
        ghost: "text-frost-muted hover:bg-plasma-wash hover:text-frost-white",
        link: "text-plasma-pink underline-offset-4 hover:underline",
      },
    },
    defaultVariants: {
      variant: "default",
    },
  }
)

function Badge({
  className,
  variant = "default",
  render,
  ...props
}: useRender.ComponentProps<"span"> & VariantProps<typeof badgeVariants>) {
  return useRender({
    defaultTagName: "span",
    props: mergeProps<"span">(
      {
        className: cn(badgeVariants({ variant }), className),
      },
      props
    ),
    render,
    state: {
      slot: "badge",
      variant,
    },
  })
}

export { Badge, badgeVariants }
