export function placeTerms(value: string): string[] | null {
  const place = findPlace(value);
  if (!place || place.value === "remote" || place.value === "worldwide") return null;
  const extra = place.iso ? EXTRA_TERMS[place.iso] : undefined;
  const terms = new Set<string>([place.label.toLowerCase(), ...(extra ?? [])]);
  return [...terms];
}
