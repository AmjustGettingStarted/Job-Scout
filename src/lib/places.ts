function jobicyFor(iso: string) {
  if (iso === "US") return "usa";
  if (iso === "GB") return "uk";
  if (iso === "CA") return "canada";
  if (EUROPE.has(iso)) return "europe";
  if (APAC.has(iso)) return "apac";
  if (LATAM.has(iso)) return "latam";
  if (AFRICA.has(iso)) return "africa";
  return undefined;
}

const countries: Place[] = COUNTRIES.map(([label, iso]) => ({
  value: label.toLowerCase(),
  label,
  iso,
  jobicy: jobicyFor(iso),
})).sort((a, b) => a.label.localeCompare(b.label));

const india = countries.find((place) => place.iso === "IN");
const rest = countries.filter((place) => place.iso !== "IN");

export const PLACES: Place[] = [
  india ?? { value: "india", label: "India", iso: "IN", jobicy: "apac" },
  { value: "remote", label: "Remote" },
  { value: "worldwide", label: "Worldwide" },
  ...rest,
];

export function findPlace(value: string) {
  const key = value.trim().toLowerCase();
  return PLACES.find((place) => place.value === key);
}

